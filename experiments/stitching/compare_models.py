"""Compare and visualize model performance: QuantaMaths (Hub) vs. RoPE (Manual).

This script compares the JSON metrics generated by `visualize_small_model_predictions.py`.

Usage:
    python experiments/stitching/compare_models.py \
        runs/stitching/qm/metrics.json \
        runs/stitching/rope/metrics.json \
        --output-plot runs/stitching/comparison.png
"""

import argparse
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


def load_json(path: str | Path) -> dict:
    with open(path) as f:
        return json.load(f)


def extract_agg_metrics(data: dict) -> dict:
    """Extract aggregated metrics from visualization JSON."""
    predictions = data.get("predictions", [])

    # Initialize per-position metrics
    # Assume 7 positions (sign + 6 digits)
    max_pos = 0
    if predictions:
        max_pos = len(predictions[0]["predictions_by_position"])

    pos_confidences = [[] for _ in range(max_pos)]
    pos_accuracies = [[] for _ in range(max_pos)]

    # Treat P/+ and M/- as equivalent for "true" accuracy
    EQUIV = {"P": "+", "+": "+", "M": "-", "-": "-"}

    total_correct_samples = 0
    for p in predictions:
        sample_correct = True
        for idx, pos_data in enumerate(p["predictions_by_position"]):
            if idx < max_pos:
                true_char = pos_data["true_character"]
                pred_char = pos_data["predicted_character"]

                # Fuzzy match for signs
                is_correct = (pred_char == true_char) or (
                    EQUIV.get(pred_char) == EQUIV.get(true_char) and true_char in EQUIV
                )

                pos_confidences[idx].append(pos_data["true_probability"])
                pos_accuracies[idx].append(1.0 if is_correct else 0.0)
                if not is_correct:
                    sample_correct = False
        if sample_correct:
            total_correct_samples += 1

    return {
        "avg_acc": (sum([np.mean(a) for a in pos_accuracies]) / max_pos * 100)
        if max_pos > 0
        else 0,
        "perfect_pct": (total_correct_samples / len(predictions)) * 100 if predictions else 0,
        "pos_conf_mean": [np.mean(c) for c in pos_confidences],
        "pos_conf_std": [np.std(c) for c in pos_confidences],
        "pos_acc": [np.mean(a) for a in pos_accuracies],
    }


def plot_comparison(qm_m: dict, rope_m: dict, output_path: str | Path):
    """Create a beautiful side-by-side comparison plot."""
    plt.style.use("seaborn-v0_8-muted")
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))

    # --- Bar Chart: Overall Accuracy ---
    labels = ["Average Accuracy", "Perfect Expressions"]
    qm_vals = [qm_m["avg_acc"], qm_m["perfect_pct"]]
    rope_vals = [rope_m["avg_acc"], rope_m["perfect_pct"]]

    x = np.arange(len(labels))
    width = 0.35

    ax1.bar(x - width / 2, qm_vals, width, label="Hub (QuantaMaths)", color="#4c72b0", alpha=0.8)
    ax1.bar(x + width / 2, rope_vals, width, label="Manual (RoPE)", color="#55a868", alpha=0.8)

    ax1.set_ylabel("Percentage (%)")
    ax1.set_title("Overall Performance Comparison", fontweight="bold", pad=20)
    ax1.set_xticks(x)
    ax1.set_xticklabels(labels)
    ax1.set_ylim(0, 110)
    ax1.legend()
    ax1.grid(axis="y", linestyle="--", alpha=0.7)

    # --- Line Chart: Confidence at Position ---
    positions = np.arange(len(qm_m["pos_conf_mean"]))

    # Hub
    ax2.plot(
        positions, qm_m["pos_conf_mean"], "o-", label="Hub Confidence", color="#4c72b0", linewidth=2
    )
    ax2.fill_between(
        positions,
        np.array(qm_m["pos_conf_mean"]) - np.array(qm_m["pos_conf_std"]),
        np.array(qm_m["pos_conf_mean"]) + np.array(qm_m["pos_conf_std"]),
        color="#4c72b0",
        alpha=0.2,
    )

    # RoPE
    ax2.plot(
        positions,
        rope_m["pos_conf_mean"],
        "s--",
        label="Manual Confidence",
        color="#55a868",
        linewidth=2,
    )
    ax2.fill_between(
        positions,
        np.array(rope_m["pos_conf_mean"]) - np.array(rope_m["pos_conf_std"]),
        np.array(rope_m["pos_conf_mean"]) + np.array(rope_m["pos_conf_std"]),
        color="#55a868",
        alpha=0.2,
    )

    ax2.set_xlabel("Output token position (0=sign, 1..6=digits)")
    ax2.set_ylabel("True Token Probability")
    ax2.set_title("Confidence by Sequence Position", fontweight="bold", pad=20)
    ax2.set_ylim(0, 1.05)
    ax2.set_xticks(positions)
    ax2.legend()
    ax2.grid(linestyle="--", alpha=0.7)

    plt.tight_layout()
    plt.savefig(output_path, dpi=150)
    print(f"Comparison plot saved to {output_path}")


def main():
    parser = argparse.ArgumentParser(description="Model comparison and visualization")
    parser.add_argument("qm_json", help="Path to Hub (QuantaMaths) JSON metrics")
    parser.add_argument("rope_json", help="Path to Manual (RoPE) JSON metrics")
    parser.add_argument(
        "--output-plot", default="runs/stitching/model_comparison.png", help="Path to save plot"
    )
    args = parser.parse_args()

    # Load data
    print(f"Loading Hub metrics: {args.qm_json}")
    qm_data = load_json(args.qm_json)
    print(f"Loading RoPE metrics: {args.rope_json}")
    rope_data = load_json(args.rope_json)

    # Extract metrics
    qm_m = extract_agg_metrics(qm_data)
    rope_m = extract_agg_metrics(rope_data)

    # Print summary table
    print("\n" + "=" * 60)
    print(f"{'Metric':<30} | {'Hub (QM)':>12} | {'Local (RoPE)':>12}")
    print("-" * 60)
    print(f"{'Avg Token Accuracy (%)':<30} | {qm_m['avg_acc']:>12.2f} | {rope_m['avg_acc']:>12.2f}")
    print(
        f"{'Perfect Expressions (%)':<30} | {qm_m['perfect_pct']:>12.2f} | {rope_m['perfect_pct']:>12.2f}"
    )
    print(
        f"{'Min Confidence (Correct Prob)':<30} | {min(qm_m['pos_conf_mean']):>12.4f} | {min(rope_m['pos_conf_mean']):>12.4f}"
    )
    print("=" * 60 + "\n")

    # Generate plot
    plot_comparison(qm_m, rope_m, args.output_plot)

    # Print example expressions
    print("\n" + "=" * 60)
    print("Example Expressions Comparison:")
    print("-" * 60)
    print(f"{'Problem':<20} | {'True Ans':>10} | {'Hub Pred':>10} | {'RoPE Pred':>10}")
    print("-" * 60)

    qm_preds = qm_data.get("predictions", [])
    rope_preds = rope_data.get("predictions", [])

    for i in range(min(5, len(qm_preds), len(rope_preds))):
        problem = qm_preds[i]["problem"]["expression"].split("=")[0] + "="
        true_ans = qm_preds[i]["true_answer"]
        hub_pred = qm_preds[i]["predicted_answer"]
        rope_pred = rope_preds[i]["predicted_answer"]
        print(f"{problem:<20} | {true_ans:>10} | {hub_pred:>10} | {rope_pred:>10}")
    print("=" * 60 + "\n")


if __name__ == "__main__":
    main()
